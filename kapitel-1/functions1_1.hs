-- Dette er min læring af kapitel 1 af bogen Programming in Haskell
-- Vi starter med funktioner. En funktion er en "mapping", som tager et eller flere argumenter eller input og producerer et enkelt resultat. 
-- Det defineres ved at en funktion gives et navn, et navn for hvert argument (ofte resultatet), og en body, som definer, hvordan input håndteres. 
-- Et eksempel fra bogen kunne være:

double x = x + x

-- Når denne funktion kaldes via ghc eller ghci ved at først aktivere miljøet og derefter kalde functionen og argumentet producerer double: 2 + 2 = 4


 
